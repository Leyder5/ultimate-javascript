// Lección 17: Declaraciones y expresiones
// (Esta clase no tiene subtítulos en Udemy; resumen del tema)

// Declaración (statement): una instrucción completa, por ejemplo crear una variable
let a = 5;

// Expresión: cualquier cosa que produce un valor
// 5 + 2      -> expresión que produce 7
// a > 3      -> expresión que produce true
let b = a + 2;   // declaración que usa la expresión "a + 2"

console.log(b);
console.log(a > 3);
